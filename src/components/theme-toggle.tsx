"use client";

import { MoonIcon, SunIcon } from "lucide-react";

import { useThemePreference } from "@/lib/theme";

/**
 * Toolbar theme switch, between light and dark.
 *
 * Reads and writes through `lib/theme.ts` rather than touching storage itself,
 * so it cannot disagree with the settings card's Theme row: both go through
 * the same store, and either one changing the theme moves the other. It also
 * means this button and the inline script in `index.html` are reading the same
 * key, which they did not when each had its own copy of the logic.
 *
 * It steps between light and dark rather than naming what it will do, because
 * there are three preferences and this one button cannot reach all of them —
 * `system` lives in the settings card. Choosing the current value would leave
 * the button dead, so the two it can reach are the two it offers.
 *
 * Deliberately mounted outside the generated thread component: thread elements
 * are regenerated by the component CLI and anything inside them can be deleted
 * without warning.
 */
export const ThemeToggle = ({ className }: { className?: string }) => {
  const [preference, setPreference] = useThemePreference();
  const goingTo = preference === "dark" ? "light" : "dark";

  return (
    <button
      type="button"
      onClick={() => setPreference(goingTo)}
      // Name the action, not the current state, so the control announces what
      // pressing it will do.
      aria-label={`Switch to ${goingTo} mode`}
      title={`Switch to ${goingTo} mode`}
      className={
        className ??
        "text-muted-foreground hover:text-foreground hover:bg-muted flex size-8 shrink-0 items-center justify-center rounded-full transition-colors focus-visible:ring-ring/50 focus-visible:ring-3 focus-visible:outline-none"
      }
    >
      {goingTo === "dark" ? (
        <MoonIcon className="size-4" aria-hidden />
      ) : (
        <SunIcon className="size-4" aria-hidden />
      )}
    </button>
  );
};