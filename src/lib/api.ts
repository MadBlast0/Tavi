/**
 * One way to every operation, whichever build this is.
 *
 * The app runs in two places: inside the Tauri shell, and in a plain browser.
 * The two reach different things — Rust on one side, a server on the other —
 * but the app above this line should not have to know which one it is in.
 *
 * This file is that line. It holds:
 *
 * - **the vocabulary** — the shapes the app and the two servers agree on;
 * - **the operations** — one function per thing the app can do, each of which
 *   picks the adapter that can do it.
 *
 * The two adapters are `src/lib/desktop.ts`, which is the only file that
 * touches `@tauri-apps/*`, and `src/lib/web.ts`, which is the only file that
 * calls `fetch("/api/…")`.
 *
 * A screen that needs to know which build it is in asks `src/lib/platform.ts`,
 * and says so in the registry of differences rather than in a branch that
 * nobody wrote down.
 */

import { openRouterCatalogue, type SlimModel } from "./catalogue.ts"
import * as desktop from "./desktop.ts"
import { isDesktopApp } from "./platform.ts"
import * as web from "./web.ts"
import type { KeyStandingReport, ProviderKey } from "./secret.ts"

export type { KeyStandingReport, ProviderKey }

/* -------------------------------------------------------------------------- */
/* The vocabulary                                                              */
/* -------------------------------------------------------------------------- */

/**
 * A folder the app has been given access to.
 *
 * On the desktop this is a path the user chose; in a browser it is a handle
 * the browser holds. Above this line it is one shape, and `src/lib/workspace.ts`
 * is what turns either into it.
 */
export type Workspace = {
  /** The folder's own id, generated by the app. */
  id: string
  /** The canonical path on disk. */
  path: string
  /** The folder's name, for display. */
  name: string
  /** When the access was granted. */
  grantedAt: number
  /** Whether the folder is still where it was. */
  missing: boolean
}

/** One entry in a folder. */
export type WorkspaceEntry = {
  /** The path, relative to the workspace, using forward slashes. */
  path: string
  /** The entry's name. */
  name: string
  /** Whether it is a directory. */
  isDirectory: boolean
  /** Its size in bytes, when it is a file. */
  size: number | null
}

/** A file's contents, read from inside a workspace. */
export type WorkspaceFile = {
  /** The path, relative to the workspace, using forward slashes. */
  path: string
  /** Its text. */
  text: string
  /** Whether it was cut short. */
  truncated: boolean
  /** How many bytes it is. */
  bytes: number
  /** Whether it is not text at all. */
  binary: boolean
}

/** A project that has been cloned. */
export type ProjectSummary = {
  /** The folder's name inside the projects folder. */
  name: string
  path: string
  /** When it was last changed. */
  modifiedAt: number
}

/** Where cloned repositories go, and what is in there. */
export type ProjectsListing = {
  root: string
  projects: ProjectSummary[]
}

/** What a clone did. */
export type CloneResult = {
  ok: boolean
  name?: string
  path?: string
  error?: string
}

/** How a clone is going. */
export type CloneProgress = {
  /** How far along it is, when git says. */
  percent?: number
  message: string
}

/** One message in a request. */
export type ChatMessage = {
  id?: string
  role: "user" | "assistant" | "system"
  parts: { type: string; text?: string }[]
}

/** The request, in the shape both servers accept. */
export type ChatRequest = {
  messages: ChatMessage[]
  /** Which surface the request came from. */
  variant: "chat" | "code"
  /** The agent mode. Code only. */
  mode?: string
  /** The folder's name. Code only. */
  folder?: string
  config?: {
    modelName?: string
    reasoningEffort?: string
  }
}

/** What the provider reported for the turn that just ended. */
export type ChatUsage = {
  inputTokens?: number
  outputTokens?: number
  totalTokens?: number
  reasoningTokens?: number
  cachedInputTokens?: number
}

/** What the servers send back as the answer arrives. */
export type ChatEvent =
  | { type: "text-delta"; delta: string }
  | {
      type: "message-metadata"
      messageMetadata?: { modelId?: string; usage?: ChatUsage }
    }
  | { type: "finish"; messageMetadata?: { modelId?: string; usage?: ChatUsage } }
  | { type: "error"; errorText: string }

/**
 * The model catalogue, and how old the copy is.
 *
 * The age is part of it because a catalogue is a list of models with prices,
 * and a copy that is three weeks old names models that no longer exist.
 * `degraded` is the one state a person can act on: the provider could not be
 * reached and this is the last good copy.
 */
export type ModelCatalogue = {
  models: SlimModel[]
  /** When the copy was fetched, in unix seconds. */
  fetchedAt: number
  /** Whether this is the last good copy rather than a current one. */
  degraded: boolean
}

/** The catalogue as the desktop's Rust command answers it. */
export type RawCatalogue = {
  /** The provider's own catalogue, as JSON. */
  body: string
  fetchedAt: number
  degraded: boolean
}

