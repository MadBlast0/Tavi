/**
 * Where the app's data is.
 *
 * On the desktop that is a folder in the app's own data directory. In a
 * browser it is the browser's storage, and there is no folder to point at.
 */
export const dataDirectory = async (): Promise<string | null> =>
  isDesktopApp() ? desktop.dataDirectory() : null
/**
 * Writes a file the user chooses.
 *
 * The desktop app asks the system where, and Rust writes it there. A browser
 * cannot ask, so the file comes down as a download instead.
 */
export const saveTextFile = async (
  name: string,
  contents: string,
): Promise<boolean> => {
  if (isDesktopApp()) {
    const path = await desktop.pickSavePath(name)
    if (!path) return false
    await desktop.writeFile(path, contents)
    return true
  }
  return web.downloadTextFile(name, contents)
}

/**
 * Reads a file the user chooses.
 *
 * The desktop app asks the system where, and Rust reads it. A browser cannot
 * ask, so the file is chosen with a file input instead.
 */
export const readTextFile = async (): Promise<string | null> => {
  if (isDesktopApp()) {
    const path = await desktop.pickOpenPath()
    if (!path) return null
    return desktop.readFile(path)
  }
  return web.chooseTextFile()
}

/**
 * Opens a page outside the app.
 *
 * The desktop's webview swallows a new-window request — a link opened with
 * `window.open` goes nowhere, because there is nowhere in the app for it to
 * go — so the page is handed to the operating system. In a browser there is
 * no operating system to hand it to, and a new tab is what the link means.
 *
 * Only https is handed over. A link that can say `file:` or `javascript:` is
 * a link that can do things the app did not mean, and the app has no reason
 * to open either.
 */
export const openExternal = async (url: string): Promise<void> => {
  let parsed: URL
  try {
    parsed = new URL(url)
  } catch {
    return
  }

  if (parsed.protocol !== "https:") {
    return
  }

  if (isDesktopApp()) {
    await desktop.openInSystemBrowser(parsed.toString())
    return
  }
  await web.openInNewTab(parsed.toString())
}
